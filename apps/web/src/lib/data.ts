export const getOverlaps = () => loadJson<OverlapResult[]>('overlaps.json');

/**
 * The curated featured set, or `null` when the bundle predates it.
 *
 * Absence is a normal state, not an error: `loadJson` throws DataMissingError on
 * a 404, and a missing *optional* file must not take the home page down with it.
 * Callers get `null` and choose their own fallback.
 */
export const getFeatured = (): Promise<FeaturedOverlap[] | null> =>
  loadJson<FeaturedOverlap[]>('featured.json')
    .then((rows) => (Array.isArray(rows) ? rows : null))
    .catch(() => null);

/** What the home page needs: the rows, the rule that picked them, and whether one was applied. */
export interface FeaturedSet {
  rows: FeaturedOverlap[];
  /** The export's own statement of the selection rule, or null if there was none. */
  note: string | null;
  /** False when this is the raw top-of-`overlaps.json` fallback, which has no rule. */
  curated: boolean;
}

/**
 * The featured set, with the fallback done here rather than in the view.
 *
 * The fallback fetch is lazy on purpose: `featured.json` is 10 KB and
 * `overlaps.json` is 2.2 MB, so a bundle that has the curated file must not pay
 * for the one it does not need. The home page used to pull the whole overlap
 * list on every visit; now it only does so on an older bundle that has nothing
 * else to show.
 */
export async function getFeaturedSet(): Promise<FeaturedSet> {
  const curated = await getFeatured();
  if (curated && curated.length > 0) {
    return {
      rows: curated,
      note: curated.find((o) => o.featureNote)?.featureNote ?? null,
      curated: true,
    };
  }
  return { rows: await getOverlaps(), note: null, curated: false };
}

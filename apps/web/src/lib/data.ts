/**
 * A curated home-page row.
 *
 * Same shape as an `overlaps.json` row, plus `featureNote` — the export's own
 * one-line statement of the rule it used to pick this set. The home page renders
 * that note verbatim rather than paraphrasing it, so the selection rule shown to
 * the reader is the selection rule the pipeline actually applied.
 *
 * `featured.json` is generated by the export step. It is deliberately optional:
 * an older bundle will not have it, and the home page falls back to the raw
 * overlap list rather than showing an error (see pages/Home.tsx).
 */
export interface FeaturedOverlap extends OverlapResult {
  featureNote?: string;
}

export interface SearchEntry {
  t: 'member' | 'bill' | 'industry' | 'recipient';
  id: string;
  label: string;
  sub: string;
  terms: string;
}

const BASE = `${import.meta.env.BASE_URL ?? './'}data/`.replace(/\/{2,}/g, '/');

const cache = new Map<string, Promise<unknown>>();

export class DataMissingError extends Error {
  constructor(public readonly file: string) {
    super(
      `Could not load ${file}. The data bundle has not been generated yet.\n\n` +
        `Run this once, from the repository root:\n\n    npm run pipeline\n\n` +
        `It needs no API keys for a first run.`,
    );
    this.name = 'DataMissingError';
  }
}

export function loadJson<T>(file: string): Promise<T> {
  const existing = cache.get(file);
  if (existing) return existing as Promise<T>;
  const p = fetch(`${BASE}${file}`)
    .then((r) => {
      if (!r.ok) throw new DataMissingError(file);
      return r.json() as Promise<T>;
    })
    .catch((err) => {
      cache.delete(file);
      if (err instanceof DataMissingError) throw err;
      throw new DataMissingError(file);
    });
  cache.set(file, p);
  return p;
}

export const getIndex = () => loadJson<BundleIndex>('index.json');
